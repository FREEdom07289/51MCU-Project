/**
 * @file    main.c
 * @brief   独立按键控制 LED 显示二进制主程序：K1 每按一次计数值加 1 并显示
 * @author  FREEDOM
 * @version V1.0
 * @date    2026-11-14
 * @note    硬件：STC89C52RC + 8 个 LED + 独立按键 K1
 *          引脚：LED 接 P2.0~P2.7（低电平点亮），K1 接 P3.1
 *          依赖模块：LED.c、KEY.c
 *          修改记录：
 *            V1.0 2026-11-14 按三层结构拆分为 Driver/System/User
 */

#include "LED.h"
#include "KEY.h"

/* ==================== 主函数 ==================== */

void main(void)
{
    unsigned char Key_Cnt = 0;      /* K1 按下次数，兼作要显示的二进制值 */

    LED_Init();

    while (1)
    {
        LED_WriteAll((unsigned char)~Key_Cnt);   /* 取反输出：值为 0 的位对应 LED 点亮 */

        if (KEY_Scan() == KEY_VALUE_K1)
        {
            Key_Cnt++;              /* 只改内存变量，不直接改端口，便于移植和调试 */
        }
    }
}

/* ==================== 实验笔记 ==================== */

/*
写代码中遇到的问题
1.读取单个引脚标准写法是P3_1或sbit P3_1 = P3^1;，而不是P3^1.
所以在main函数中检测按键是否按下的条件应该是if(P3_1==0)而不是if(P3^1==0)
2.应先定义独立软件变量K1NUM来记录按键按下次数，每次按键松开执行K1NUM++，只修改内存中的变量K1NUM的值，而不是直接修改P2口的值。
*/

/*
不直接修改P2口的值的原因：
1. P2是硬件寄存器，不止控制LED灯。单片机运行中P2会受硬件，其他代码改写，存不住稳定的按键次数。
2. 通过修改K1NUM变量的值，可以更好地控制LED灯的状态，同时也可以方便地进行调试和维护。
3. 直接修改P2口的值可能会导致程序的可读性和可维护性降低，而使用K1NUM变量可以使代码更清晰易懂。  
 */
