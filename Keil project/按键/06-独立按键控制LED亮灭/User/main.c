/**
 * @file    main.c
 * @brief   独立按键控制 LED 亮灭主程序：K1 每按一次翻转一次 D1
 * @author  FREEDOM
 * @version V1.0
 * @date    2026-11-14
 * @note    硬件：STC89C52RC + LED D1 + 独立按键 K1
 *          引脚：D1 接 P2.0（低电平点亮），K1 接 P3.1
 *          依赖模块：LED.c、KEY.c
 *          修改记录：
 *            V1.0 2026-11-14 按三层结构拆分为 Driver/System/User
 */

#include "LED.h"
#include "KEY.h"

/* ==================== 主函数 ==================== */

void main(void)
{
    LED_Init();                 /* 上电默认熄灭 D1 */

    while (1)
    {
        if (KEY_Scan() == KEY_VALUE_K1)
        {
            LED_Toggle();       /* 每确认一次按下，翻转一次 D1 */
        }
    }
}

/* ==================== 实验笔记 ==================== */

/* 说明：
 * 1. 按键K1按下时，LED1状态翻转（亮→灭→亮→灭…）。
 * 2. 使用消抖延迟函数Delay20ms()来避免按键抖动导致的误触发。
 * 3. LED1初始状态为熄灭（高电平），按下K1后会点亮（低电平）。
 */

/*  写代码过程中的错误总结
 *  错误1：按键消抖处理的延迟函数时间不够，导致按键抖动引起误触发。
 *  错误2：未写按键松开等待的逻辑，代码检测到一次 KEY1==0 之后就直接翻转如果还没等到手松开，下一次循环可能又读到一次按下或抖动，结果表现不稳定。
 *  错误3：LED初始状态设置错误，导致第一次按下按键时LED状态不符合预期。（IO口都有上拉电阻，所以初始状态应该为高电平）
 */
